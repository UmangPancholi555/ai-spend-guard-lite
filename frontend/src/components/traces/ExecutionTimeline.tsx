import { useState } from 'react';
import type { Source, TimelineEntry } from '@shared/types';
import { Badge, StatusBadge } from '../ui/Badge';
import { fmtMs } from '../../lib/format';
import { JsonBlock, fmtDateTimeMs } from '../observability/common';

export const STEP_LABELS: Record<TimelineEntry['step'], string> = {
  'execution.started': 'Execution started',
  'context.initialized': 'Context initialized',
  'memory.injection.started': 'Memory injection started',
  'memory.injection.completed': 'Memory injection completed',
  'memory.injection.failed': 'Memory injection failed',
  'bus.operation': 'Bus operation executed',
  'tool.call.initiated': 'Tool call initiated',
  'tool.call.completed': 'Tool call completed',
  'tool.call.failed': 'Tool call failed',
  'context.event': 'Context event',
  'response.generated': 'Response generated',
  'execution.completed': 'Execution completed',
  'execution.failed': 'Execution failed',
  span: 'Span',
  other: 'Event',
};

/** Prominent, unambiguous provenance marker: amber DEMO / SIMULATED vs purple ACTUAL. */
function ProvenanceBadge({ source }: { source: Source }) {
  return (
    <span data-testid="timeline-source" data-source={source}>
      {source === 'SIMULATED'
        ? <Badge tone="amber">DEMO / SIMULATED</Badge>
        : <Badge tone="purple">ACTUAL</Badge>}
    </span>
  );
}

function Entry({ e }: { e: TimelineEntry }) {
  const [open, setOpen] = useState(false);
  const failed = e.status === 'FAILURE';
  const dot = failed ? 'bg-red-500' : e.status === 'SUCCESS' ? 'bg-emerald-500' : e.status === 'STARTED' ? 'bg-blue-500' : 'bg-slate-400';
  return (
    <li data-testid="timeline-entry" data-step={e.step} data-status={e.status} data-source={e.source}
      className={`relative pl-7 ${failed ? 'rounded-md bg-red-50 py-1 pr-2 dark:bg-red-950/30' : ''}`}>
      <span aria-hidden="true" className={`absolute left-1.5 top-3 h-2.5 w-2.5 rounded-full ring-4 ring-white dark:ring-slate-900 ${dot}`} />
      <button type="button" aria-expanded={open} onClick={() => setOpen(o => !o)} data-testid="timeline-entry-toggle"
        className="flex w-full flex-wrap items-center gap-x-3 gap-y-1 rounded px-1 py-1.5 text-left hover:bg-slate-50 dark:hover:bg-slate-800/50">
        <span className="font-mono text-xs text-slate-600 dark:text-slate-400">{fmtDateTimeMs(e.ts)}</span>
        <span className={`text-sm font-semibold ${failed ? 'text-red-800 dark:text-red-200' : ''}`} data-testid="timeline-step">{STEP_LABELS[e.step] ?? e.step}</span>
        <span className="min-w-0 truncate text-sm text-slate-600 dark:text-slate-300">{e.label}</span>
        <span className="ml-auto flex flex-wrap items-center gap-2">
          <ProvenanceBadge source={e.source} />
          <StatusBadge status={e.status} />
          {failed && <span data-testid="timeline-entry-failed"><Badge tone="red">FAILED</Badge></span>}
          <span className="w-14 text-right text-xs tabular-nums text-slate-600 dark:text-slate-300">{fmtMs(e.durationMs)}</span>
        </span>
      </button>
      {failed && e.errorMessage && <div className="px-1 pb-1 text-sm text-red-700 dark:text-red-300" role="alert" data-testid="timeline-error">{e.errorMessage}</div>}
      {open && (
        <div className="px-1 pb-3" data-testid="timeline-details">
          <div className="mb-1 text-xs text-slate-600 dark:text-slate-400">{e.refKind}{e.refId ? ` ${e.refId}` : ''}{e.spanId ? ` - span ${e.spanId}` : ''} - metadata only, no content is stored</div>
          <JsonBlock data={e.details} label="Timeline entry details" />
        </div>
      )}
    </li>
  );
}

export default function ExecutionTimeline({ entries }: { entries: TimelineEntry[] }) {
  if (entries.length === 0) return <div className="p-6 text-center text-sm text-slate-600 dark:text-slate-400" data-testid="empty-state">No timeline entries recorded for this trace.</div>;
  const simulated = entries.filter(e => e.source === 'SIMULATED').length;
  return (
    <div>
      {simulated > 0 && (
        <p className="mb-3 rounded-md border border-amber-300 bg-amber-50 p-2 text-xs text-amber-900 dark:border-amber-800 dark:bg-amber-950/40 dark:text-amber-200" data-testid="timeline-simulated-note">
          {simulated} of {entries.length} entries are DEMO / SIMULATED: generated by the simulator or the mock provider, not emitted by a real memory, tool or context runtime. Entries marked ACTUAL come from real instrumented code in this app.
        </p>
      )}
      <ol className="relative space-y-1 before:absolute before:bottom-2 before:left-[10px] before:top-2 before:w-px before:bg-slate-200 dark:before:bg-slate-700" data-testid="timeline">
        {entries.map((e, i) => <Entry key={`${e.ts}-${e.refId ?? i}-${i}`} e={e} />)}
      </ol>
    </div>
  );
}
