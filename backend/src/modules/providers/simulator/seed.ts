/** POST /simulations/seed: deterministic backdated DEMO data through the normal pipeline. */
import type { AppDeps } from '../../../contracts/services';
import type { SimulatedFailure, SimulationSeedRequest } from '../../../../../shared/types';
import { conflict } from '../../../utils/errors';
import { executeMockRequest, loadActiveProject } from '../pipeline';
import { fillerText, mulberry32, pick, pickWeighted, randInt, seedFromString } from '../mock/prng';
import { MOCK_PROVIDER_KEYS, SIM_LABEL, getMockProvider } from '../mock';

export const DEMO_PROJECT_NAME = 'Demo Project (simulated)';
const AGENT_TRACE_CAP = 25;
const DAY_MS = 86_400_000;

export interface SeedResult { taskId: string; created: number; projectId: string; failures: number }

async function resolveProject(deps: AppDeps, projectId?: string): Promise<{ id: string; name: string }> {
  if (projectId) return loadActiveProject(deps, projectId);
  const existing = await deps.prisma.project.findFirst({ where: { name: DEMO_PROJECT_NAME } });
  if (existing) {
    if (existing.status !== 'ACTIVE') throw conflict(`Project "${DEMO_PROJECT_NAME}" is archived; unarchive it or pass projectId`, { projectId: existing.id });
    return existing;
  }
  const created = await deps.prisma.project.create({
    data: { name: DEMO_PROJECT_NAME, description: 'Demo data generated by the simulator (DEMO / SIMULATED)', isTest: true },
  });
  await deps.instr.recordActivity({
    type: 'project.created', level: 'INFO', source: 'SIMULATED', projectId: created.id,
    message: `Demo project "${DEMO_PROJECT_NAME}" created by the simulator`, metadata: { simulated: true, label: SIM_LABEL, isTest: true },
  });
  return created;
}

interface Plan { createdAt: Date; provider: 'openai' | 'anthropic'; model: string; promptChars: number; maxOutputTokens: number; temperature: number; failure: SimulatedFailure }

export async function runSeed(deps: AppDeps, input: SimulationSeedRequest & { seed?: string | number }): Promise<SeedResult> {
  const includeFailures = input.includeFailures ?? true;
  const project = await resolveProject(deps, input.projectId);

  const task = await deps.instr.startTask({ name: `Demo data seed (${input.requests} requests / ${input.spreadDays}d)`, kind: 'DEMO_SEED', source: 'SIMULATED' });
  try {
    const seedKey = `seed|${input.seed ?? 'default'}|${input.requests}|${input.spreadDays}|${includeFailures}|${input.includeAgentActivity ?? false}`;
    const rng = mulberry32(seedFromString(seedKey));

    // model pools from DB (active models), falling back to the built-in mock catalog
    const dbModels = await deps.prisma.model.findMany({ where: { active: true }, include: { provider: true } });
    const pools = new Map<string, string[]>();
    for (const key of MOCK_PROVIDER_KEYS) {
      const names = dbModels.filter(m => m.provider.key === key).map(m => m.name).sort();
      pools.set(key, names.length ? names : getMockProvider(key).listModels().map(m => m.name));
    }

    const now = Date.now();
    const plans: Plan[] = [];
    for (let i = 0; i < input.requests; i++) {
      const provider = pick(rng, MOCK_PROVIDER_KEYS);
      const models = pools.get(provider)!;
      // cheaper/smaller models appear more often: weight decreases with list position
      const model = rng() < 0.03 ? 'experimental-preview-x' : pickWeighted(rng, models.map((m, idx) => ({ value: m, weight: models.length - idx + 1 })));
      // business-hours-weighted instant within the spread window
      const dayOffset = Math.floor(rng() * input.spreadDays);
      const hour = pickWeighted(rng, Array.from({ length: 24 }, (_, h) => ({ value: h, weight: h >= 8 && h <= 19 ? 5 : 1 })));
      const base = new Date(now - dayOffset * DAY_MS);
      base.setUTCHours(hour, randInt(rng, 0, 59), randInt(rng, 0, 59), randInt(rng, 0, 999));
      const createdAt = new Date(Math.min(base.getTime(), now - 1000));
      const sizeClass = pickWeighted(rng, [{ value: 'short', weight: 55 }, { value: 'medium', weight: 30 }, { value: 'long', weight: 15 }]);
      const promptChars = sizeClass === 'short' ? randInt(rng, 20, 190) : sizeClass === 'medium' ? randInt(rng, 220, 1500) : randInt(rng, 1500, 8000);
      const maxOutputTokens = pick(rng, [64, 128, 256, 256, 512, 1024, 2048]);
      const temperature = Math.round(rng() * 10) / 10 * 1.2;
      const failRoll = rng();
      const failure: SimulatedFailure = includeFailures && failRoll < 0.06
        ? pickWeighted<SimulatedFailure>(rng, [{ value: 'error', weight: 50 }, { value: 'timeout', weight: 25 }, { value: 'rate_limit', weight: 25 }])
        : 'none';
      plans.push({ createdAt, provider, model, promptChars, maxOutputTokens, temperature: Math.round(temperature * 100) / 100, failure });
    }
    plans.sort((a, b) => a.createdAt.getTime() - b.createdAt.getTime());

    const traceFrom = input.includeAgentActivity ? Math.max(0, plans.length - AGENT_TRACE_CAP) : plans.length; // most recent <=25
    let failures = 0;
    for (let i = 0; i < plans.length; i++) {
      const p = plans[i]!;
      const withAgent = i >= traceFrom;
      const prompt = `Simulated demo prompt #${i}. ` + fillerText(rng, Math.max(1, p.promptChars - 24)); // transient; never stored
      const res = await executeMockRequest(deps, {
        projectId: project.id, provider: p.provider, model: p.model, prompt, maxOutputTokens: p.maxOutputTokens,
        temperature: p.temperature, simulateFailure: p.failure, simulateAgentActivity: withAgent,
      }, {
        createdAt: p.createdAt, traceSource: 'SIMULATED', trace: withAgent, activity: false, latency: false, runtime: 'silent', injectMemory: false,
        project, extraMetadata: { seeded: true, seedTaskId: task.id, backdated: true },
      });
      if (res.status === 'FAILURE') failures++;
    }

    await deps.instr.recordActivity({
      type: 'simulation.seeded', level: 'INFO', source: 'SIMULATED', projectId: project.id,
      message: `Simulator generated ${plans.length} backdated demo requests over ${input.spreadDays} days`,
      metadata: { simulated: true, label: SIM_LABEL, created: plans.length, failures, spreadDays: input.spreadDays, taskId: task.id, includeAgentActivity: !!input.includeAgentActivity },
    });
    await task.succeed({
      simulated: true, label: SIM_LABEL, created: plans.length, failures, projectId: project.id,
      spreadDays: input.spreadDays, includeFailures, includeAgentActivity: !!input.includeAgentActivity,
      agentTraces: Math.min(AGENT_TRACE_CAP, input.includeAgentActivity ? plans.length : 0),
    });
    return { taskId: task.id, created: plans.length, projectId: project.id, failures };
  } catch (e) {
    await task.fail(e).catch(() => undefined);
    throw e;
  }
}
